def build2():
    res = M.build()
    for g in res:
        for k, loc in PLACE2[g].items():
            res[g].setdefault(loc, dict(main='', boxes=[]))['boxes'].append(link_box(g, k))
        for loc, bl in DEEP2[g].items():
            e = res[g].setdefault(loc, dict(main='', boxes=[]))
            # 「より深く」は、つながりの箱より前に
            nl = [b for b in e['boxes'] if b['kind'] == 'link' and b['title'] not in [x['title'] for x in bl]]
            e['boxes'] = [b for b in e['boxes'] if b['kind'] == 'deep'] + bl + [b for b in e['boxes'] if b['kind'] == 'link']
        for loc, m in MAIN2[g].items():
            e = res[g].setdefault(loc, dict(main='', boxes=[]))
            assert not e['main'], ('main重複', g, loc)
            e['main'] = m
    return res
