def autosize(lines, maxw, sizes=(17, 16, 15, 14, 13)):
    for z in sizes:
        if all(tw(l, z) <= maxw for l in lines): return z
    raise AssertionError(f'fit失敗: {lines} maxw={maxw}')

def grid(name, alt, colx, head, rows, first_color=DEEP, hdr=DEEP, red_cells=(), foot=None, W=560, rowpad=14):
    """colx: [(左x, 幅)] / head: 見出し文字列のリスト / rows: セルのリスト（'\\n'で改行、('文字',色)で色指定）"""
    b = []; y = 12
    b.append(rect(12, y, 536, 40, hdr, hdr, 2, 10))
    for (x, w), h in zip(colx, head):
        if h: b.append(t(x + w / 2, y + 26, h, 17, '#fff', 'bold', 'middle'))
    y += 46
    for ri, row in enumerate(rows):
        cells = []
        for ci, c in enumerate(row):
            s, col = (c if isinstance(c, tuple) else (c, None))
            ls = s.split('\n'); x, w = colx[ci]
            z = autosize(ls, w - 14, (17, 16, 15, 14, 13) if ci else (18, 17, 16, 15, 14, 13))
            cells.append((ls, z, col, x, w))
        nl = max(len(c[0]) for c in cells); zz = max(c[1] for c in cells)
        h = rowpad * 2 + nl * (zz + 7) - 7
        b.append(rect(12, y, 536, h, WASH if ri % 2 == 0 else '#fff', LINE, 1.5, 8))
        for ci, (ls, z, col, x, w) in enumerate(cells):
            tot = len(ls) * (z + 7) - 7; y0 = y + (h - tot) / 2 + z * 0.82
            for k, l in enumerate(ls):
                b.append(t(x + w / 2, y0 + k * (z + 7), l, z, col or (first_color if ci == 0 else INK), 'bold' if (ci == 0 or col) else 'normal', 'middle'))
        y += h + 6
    if foot:
        fz = autosize([foot], 506, (17, 16, 15))
        b.append(rect(12, y + 2, 536, 38, YELP, YEL, 2, 8)); b.append(t(28, y + 27, foot, fz, INK, 'bold')); y += 44
    save(name, S(W, y + 8, b, alt))

