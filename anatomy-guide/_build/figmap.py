def apply_figs(chapters):
    found = set()
    for ch in chapters:
        for p in ch['points']:
            if p['title'] in FIGMAP:
                name, alt, cap = FIGMAP[p['title']]
                p['anchor'] = p['anchor'] + FIG(name, alt, cap)
                found.add(p['title'])
    missing = set(FIGMAP) - found
    assert not missing, f'figmap: title not found: {missing}'
